#pragma once

#include <QString>
#include <QStringList>
#include <QVector>

// Разбор CSV-выгрузок (например, отчёта "Остатки" из МойСклад, сохранённого
// как CSV). Сам файл может быть в самых разных видах - разный разделитель,
// разная кодировка, лишние строки преамбулы перед настоящими заголовками -
// поэтому парсер отдаёт "сырые" строки, а решение о том, где заголовки и
// какая колонка что означает, принимает пользователь в ImportTab.
namespace CsvImport {

struct Table {
    QVector<QStringList> rows;
    bool ok = false;
    QString error;
};

// Читает файл, автоматически определяя разделитель (';' или ',') и
// кодировку (UTF-8, а если это не похоже на валидный UTF-8 - Windows-1251,
// в которой Excel часто сохраняет CSV в русской локали). Понимает кавычки
// по RFC4180, включая многострочные значения внутри кавычек.
Table readFile(const QString &path);

} // namespace CsvImport
