#pragma once

#include <QString>

// Какая это сборка программы. Номер сборки и коммит подставляет CI (CMake: -DAPP_BUILD=<номер запуска>,
// -DAPP_COMMIT=<короткий хеш>); у локальной сборки номер 0. По номеру программа понимает, что на GitHub появилась
// более новая сборка (src/updater.cpp).
namespace AppVersion {

// Номер сборки; 0 - собрано не в CI («версия для разработки»). Для тестов подменяется переменной INVENTORY_FAKE_BUILD.
int build();
// Короткий хеш коммита сборки (пусто, если неизвестен).
QString commit();
// Дата сборки программы: «23.10.2026».
QString builtOn();
// «сборка 56 (ce4294e)» или «версия для разработки».
QString text();

} // namespace AppVersion
